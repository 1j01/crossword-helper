def count_isolated_cells(matrix: list[list[bool]]) -> int:
	height = len(matrix)
	width = len(matrix[0])
	isolated_count = 0

	for y in range(height):
		for x in range(width):
			if not matrix[y][x]:
				neighbors = [
					(y-1, x), (y+1, x),
					(y, x-1), (y, x+1)
				]
				if all(
					ny < 0 or ny >= height or nx < 0 or nx >= width or matrix[ny][nx]
					for ny, nx in neighbors
				):
					isolated_count += 1
	return isolated_count

